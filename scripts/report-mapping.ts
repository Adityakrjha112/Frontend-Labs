/**
 * Expands src/roadmap/question-map.ts into docs/roadmap-question-mapping.md
 * so the mapping can be reviewed question by question.
 * Usage: npm run report:mapping
 */
import { writeFile } from "node:fs/promises";
import data from "../src/data/questions.json";
import type { QuestionBank } from "../src/lib/types";
import { TOPICS } from "../src/roadmap/model";
import { PARTIAL_COVERAGE, resolveMapping, UNMAPPED_WEEKS, WEEK_RULES } from "../src/roadmap/question-map";

const { questions } = data as QuestionBank;
const m = resolveMapping(questions);
if (m.dangling.length) {
  console.error(`Mapping rules match nothing:\n  ${m.dangling.join("\n  ")}`);
  process.exit(1);
}
const byId = new Map(questions.map((q) => [q.id, q]));
const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const out: string[] = [
  "# Roadmap ↔ question mapping",
  "",
  "Generated by `npm run report:mapping` from `src/roadmap/question-map.ts`. Do not edit by hand.",
  "",
  `- Questions in the workbook: **${questions.length}**`,
  `- Linked to at least one roadmap week: **${m.byQuestion.size}**`,
  `- Not linked: **${questions.length - m.byQuestion.size}**`,
  `- Weeks without questions: **${Object.keys(UNMAPPED_WEEKS).length}** (${Object.keys(UNMAPPED_WEEKS).join(", ")})`,
  "",
  "## Weeks",
  "",
];
for (const t of TOPICS) {
  const ids = m.byWeek.get(t.id) ?? [];
  out.push(`### W${t.week} · ${t.title} — ${ids.length} question${ids.length === 1 ? "" : "s"}`, "");
  const rules = WEEK_RULES[t.id];
  if (!rules) {
    out.push(`Unmapped: ${UNMAPPED_WEEKS[t.id]}`, "");
    continue;
  }
  for (const r of rules) {
    const sel = [...(r.topics ?? []).map(([p, tp]) => `\`${p} · ${tp}\``), ...(r.ids ?? []).map((i) => `\`${i}\``)].join(", ");
    out.push(`- ${sel} → ${r.why}`);
  }
  if (PARTIAL_COVERAGE[t.id]) out.push(`- _Partial coverage:_ ${PARTIAL_COVERAGE[t.id]}`);
  out.push("", "| ID | Type | Topic / Subtopic | Question |", "| --- | --- | --- | --- |");
  for (const id of ids) {
    const q = byId.get(id)!;
    out.push(`| ${q.id} | ${q.type} | ${esc(q.topic)} / ${esc(q.subtopic)} | ${esc(q.question)} |`);
  }
  out.push("");
}
out.push("## Questions not linked to any week", "", "| ID | Workbook topic / subtopic | Question |", "| --- | --- | --- |");
for (const q of questions.filter((x) => !m.byQuestion.has(x.id))) {
  out.push(`| ${q.id} | ${esc(q.topic)} / ${esc(q.subtopic)} | ${esc(q.question)} |`);
}
await writeFile("docs/roadmap-question-mapping.md", out.join("\n") + "\n");
console.log(`Wrote docs/roadmap-question-mapping.md (${m.byQuestion.size} linked, ${questions.length - m.byQuestion.size} unlinked).`);
